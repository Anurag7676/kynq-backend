// Random question from deck+level not in `exclude`; falls back to any in that
// level if all are excluded. Unknown deck → "general"; level clamped to 1..3.
export function pickPairQuestion(deck, level, exclude = new Set()) {
  const d = PAIR_DECKS.includes(deck) ? deck : "general";
  const n = Math.round(Number(level));
  const lvl = Number.isFinite(n) ? Math.min(3, Math.max(1, n)) : 1;
  const list = PAIR_QUESTIONS[d][lvl];
  const fresh = exclude && exclude.size ? list.filter((q) => !exclude.has(q)) : list;
  const pool = fresh.length ? fresh : list;
  return pool[Math.floor(Math.random() * pool.length)];
}
